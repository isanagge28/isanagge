#!/usr/bin/env bash
# Isana: подсказка Claude при старте сессии.
# Только читает. Ничего не пишет, не ставит и не ходит в интернет.
ROOT="${CLAUDE_PLUGIN_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
VER=$(sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$ROOT/.claude-plugin/plugin.json" 2>/dev/null | head -1)
CFG="$HOME/.isanagge/config.json"
BRAIN=""
if [ -f "$CFG" ]; then
  BRAIN=$(sed -n 's/.*"brain"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$CFG" | head -1 | sed 's/\\\\/\\/g')
fi
PC=$(hostname -s 2>/dev/null || hostname 2>/dev/null || echo "компьютер")

echo "[Isana ${VER:-?}] Плагин isanagge (Второй мозг) включён. На вопрос «какая версия Isana» отвечай: ${VER:-?}."
if [ -n "$BRAIN" ] && [ -d "$BRAIN" ]; then
  echo "Второй мозг человека лежит здесь: $BRAIN (этот компьютер: $PC)"
  echo "ГЛАВНОЕ ПРАВИЛО: всё, что создаёшь (документы, тексты, таблицы, программы, сайты, видео, скачанное), сохраняй только во Втором мозге: документы — $BRAIN/Документы/, проекты — $BRAIN/Проекты/<Название>/ (большой проект с кодом или тяжёлыми медиа — только карточка со ссылкой, см. isanagge:novyy-proekt), входящие файлы и голосовые — $BRAIN/Входящие/. Не сохраняй на Рабочий стол, в Загрузки и временные папки без прямой просьбы. После каждого нового файла добавь строку в $BRAIN/index.md."
  echo "Перед работой прочитай $BRAIN/CLAUDE.md и $BRAIN/index.md. Уроки и ошибки записывай в $BRAIN/feedback.md. Удачный приём предложи сохранить навыком (isanagge:zapomni-priem). Голосовые и аудио расшифровывай навыком isanagge:rasshifrovka. Ссылки и видео, которые прислал человек, открывай и смотри навыком isanagge:watch."
  echo "НАПОМИНАНИЕ ПЕРЕД РАБОТОЙ: прежде чем создать файл или папку, реши, куда он ляжет (Документы/, Проекты/<Название>/ или Входящие/), и клади сразу туда, а не в корень. Если работа относится к существующему проекту — в его папку. После — строка в index.md. Навести порядок в уже лежащем — навык isanagge:sortirovka."
  echo "ЖУРНАЛ: после заметной работы и на «на сегодня всё», «закончили», «пока» добавь запись СВЕРХУ в $BRAIN/журнал.md: «## <ГГГГ-ММ-ДД ЧЧ:ММ> · $PC», ниже 2–4 строки: что сделали, что осталось, следующий шаг, в каком проекте."

  # Где остановились: последние записи журнала (новые сверху).
  if [ -f "$BRAIN/журнал.md" ]; then
    LAST=$(awk '/^## /{c++} c>=1 && c<=3' "$BRAIN/журнал.md" 2>/dev/null | head -n 30)
    if [ -n "$LAST" ]; then
      echo "ГДЕ ОСТАНОВИЛИСЬ (последние записи журнала):"
      echo "$LAST"
      echo "Если человек не начал с конкретной просьбы — в первом ответе одной-двумя фразами напомни, где остановились (и на каком компьютере), и спроси, продолжаем ли."
    fi
  fi

  # Приёмы: главная копия во Втором мозге (Навыки/<имя>/SKILL.md), рабочая — в ~/.claude/skills/<имя>/.
  NEWSK=""; CHGSK=""
  if [ -d "$BRAIN/Навыки" ]; then
    for d in "$BRAIN/Навыки"/*/; do
      [ -f "${d}SKILL.md" ] || continue
      n=$(basename "$d")
      t="$HOME/.claude/skills/$n/SKILL.md"
      if [ ! -f "$t" ]; then NEWSK="$NEWSK $n"
      elif ! cmp -s "${d}SKILL.md" "$t"; then CHGSK="$CHGSK $n"; fi
    done
  fi
  if [ -n "$NEWSK" ] || [ -n "$CHGSK" ]; then
    echo "ПРИЁМЫ ИЗ ВТОРОГО МОЗГА ещё не подключены на этом компьютере. Новые:${NEWSK:- нет}. Изменённые:${CHGSK:- нет}. Одной строкой предложи подключить (навык isanagge:sinhronizaciya, раздел «Навыки»); без согласия не копируй."
  fi

  # Только считаем неразобранное, ничего не трогаем.
  INBOX=0
  if [ -d "$BRAIN/Входящие" ]; then
    INBOX=$(find "$BRAIN/Входящие" -mindepth 1 -maxdepth 1 ! -name '.*' ! -name '_Разобрать' 2>/dev/null | wc -l | tr -d ' ')
  fi
  LOOSE=$(find "$BRAIN" -mindepth 1 -maxdepth 1 ! -name '.*' ! -name 'desktop.ini' ! -name 'Icon?' \
    ! -name 'CLAUDE.md' ! -name 'index.md' ! -name 'ссылки.md' ! -name 'feedback.md' ! -name 'журнал.md' \
    ! -name 'Документы' ! -name 'Входящие' ! -name 'Навыки' ! -name 'Проекты' 2>/dev/null | wc -l | tr -d ' ')
  if [ "${INBOX:-0}" -gt 0 ] || [ "${LOOSE:-0}" -gt 0 ]; then
    echo "Неразобрано: во Входящих — ${INBOX:-0}, в корне Второго мозга — ${LOOSE:-0}. В первом ответе одной строкой предложи разложить по папкам (навык isanagge:sortirovka); без согласия ничего не перемещай. Срочную просьбу человека сделай сначала."
  fi
elif [ -n "$BRAIN" ]; then
  echo "Второй мозг записан по пути «$BRAIN», но сейчас эта папка недоступна. Обычно это значит, что облако (Google Диск, iCloud, Dropbox, OneDrive) не запущено, ещё не синхронизировалось или диск не подключён. НЕ создавай новый Второй мозг. В первом ответе скажи об этом человеку и попроси запустить облако или подключить диск; если Второй мозг переехал — навык isanagge:sinhronizaciya, раздел «Подключить существующий»."
else
  echo "Второго мозга на этом компьютере ещё нет. В первом ответе поздоровайся и предложи создать папку «Второй мозг» или подключить уже существующую из облака (если человек работает на нескольких компьютерах) — вызови навык isanagge:start. Ничего не создавай без согласия."
fi
exit 0
