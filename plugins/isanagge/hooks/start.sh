#!/usr/bin/env bash
# Isana: подсказка Claude при старте сессии.
# Только читает. Ничего не пишет, не ставит и не ходит в интернет.
ROOT="${CLAUDE_PLUGIN_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
VER=$(sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$ROOT/.claude-plugin/plugin.json" 2>/dev/null | head -1)
CFG="$HOME/.isanagge/config.json"
BRAIN=""
if [ -f "$CFG" ]; then
  BRAIN=$(sed -n 's/.*"brain"[[:space:]]*:[[:space:]]*"\(.*\)".*/\1/p' "$CFG" | head -1 | sed 's/\\\\/\\/g')
fi

echo "[Isana ${VER:-?}] Плагин isanagge (Второй мозг) включён. На вопрос «какая версия Isana» отвечай: ${VER:-?}."
if [ -n "$BRAIN" ] && [ -d "$BRAIN" ]; then
  echo "Второй мозг человека лежит здесь: $BRAIN"
  echo "ГЛАВНОЕ ПРАВИЛО: всё, что создаёшь (документы, тексты, таблицы, программы, сайты, видео, скачанное), сохраняй только во Втором мозге: документы — $BRAIN/Документы/, программы и проекты — $BRAIN/Проекты/<Название>/, входящие файлы и голосовые — $BRAIN/Входящие/. Не сохраняй на Рабочий стол, в Загрузки и временные папки без прямой просьбы. После каждого нового файла добавь строку в $BRAIN/index.md."
  echo "Перед работой прочитай $BRAIN/CLAUDE.md и $BRAIN/index.md. Новые проекты создавай в $BRAIN/Проекты/ (навык isanagge:novyy-proekt). Уроки и ошибки записывай в $BRAIN/feedback.md. Удачный приём предложи сохранить навыком (isanagge:zapomni-priem). Голосовые и аудио расшифровывай навыком isanagge:rasshifrovka. Ссылки и видео, которые прислал человек, открывай и смотри навыком isanagge:watch."
  echo "НАПОМИНАНИЕ ПЕРЕД РАБОТОЙ: прежде чем создать файл или папку, реши, куда он ляжет (Документы/, Проекты/<Название>/ или Входящие/), и клади сразу туда, а не в корень. Если работа относится к существующему проекту — в его папку. После — строка в index.md. Навести порядок в уже лежащем — навык isanagge:sortirovka."
  # Только считаем неразобранное, ничего не трогаем.
  INBOX=0
  if [ -d "$BRAIN/Входящие" ]; then
    INBOX=$(find "$BRAIN/Входящие" -mindepth 1 -maxdepth 1 ! -name '.*' ! -name '_Разобрать' 2>/dev/null | wc -l | tr -d ' ')
  fi
  LOOSE=$(find "$BRAIN" -mindepth 1 -maxdepth 1 ! -name '.*' \
    ! -name 'CLAUDE.md' ! -name 'index.md' ! -name 'ссылки.md' ! -name 'feedback.md' \
    ! -name 'Документы' ! -name 'Входящие' ! -name 'Навыки' ! -name 'Проекты' 2>/dev/null | wc -l | tr -d ' ')
  if [ "${INBOX:-0}" -gt 0 ] || [ "${LOOSE:-0}" -gt 0 ]; then
    echo "Неразобрано: во Входящих — ${INBOX:-0}, в корне Второго мозга — ${LOOSE:-0}. В первом ответе одной строкой предложи разложить по папкам (навык isanagge:sortirovka); без согласия ничего не перемещай. Срочную просьбу человека сделай сначала."
  fi
else
  echo "Второго мозга у человека ещё нет. В первом ответе поздоровайся и предложи создать папку «Второй мозг» — вызови навык isanagge:start. Ничего не создавай без согласия."
fi
exit 0
