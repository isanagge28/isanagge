#!/usr/bin/env bash
# Проверка шаблонов Второго мозга. Запуск: bash tests/test-templates.sh
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
T="$ROOT/plugins/isanagge/templates"
fail=0
has() { if grep -qF -- "$2" "$1" 2>/dev/null; then echo "PASS: $(basename "$1") — $2"; else echo "FAIL: $(basename "$1") — нет «$2»"; fail=1; fi; }
for f in CLAUDE.md index.md ссылки.md feedback.md; do
  [ -f "$T/$f" ] && echo "PASS: есть $f" || { echo "FAIL: нет $f"; fail=1; }
done
for s in "## Кто я" "## Чем занимаюсь" "## Как со мной работать" "## Как устроен Второй мозг" "## Подсказки по навыкам" "## Где всё хранить"; do has "$T/CLAUDE.md" "$s"; done
has "$T/CLAUDE.md" "Запомни что с этого момента не принимай мои выводы за истину. Твоя цель быть интеллектуальным оппонентом, а не ассистентом, который со всем соглашается."
has "$T/CLAUDE.md" "Каждый раз, когда я говорю о своей идее делай так: анализируй мои предположения, предоставляй контр-аргументы, проверяй мою логику, предлагай альтернативы и ставь истину выше согласия."
has "$T/CLAUDE.md" "Поддерживай конструктивный, строгий подход. Твоя роль не спорить ради спора, а помочь мне добиваться большей ясности"
has "$T/CLAUDE.md" "Запомни это для всех наших будущих диалогов неизменно"
exit $fail
